/** The app icon: the pill's dot and waveform on its dark tile. */
export function VoxMark(props: { size?: number }) {
  const bars = [
    [20.54, 14.35],
    [30.73, 23.71],
    [40.93, 38.27],
    [51.12, 26.83],
    [61.31, 50.75],
    [71.5, 33.07],
    [81.69, 20.59],
    [91.89, 13.31],
  ];
  const tile = createUniqueId();
  return (
    <svg width={props.size ?? 28} height={props.size ?? 28} viewBox="0 0 104 104" aria-hidden="true">
      <defs>
        <linearGradient id={tile} x1="0" y1="0" x2="0" y2="1">
          <stop offset="0%" stop-color="#24293b" />
          <stop offset="100%" stop-color="#0f121c" />
        </linearGradient>
      </defs>
      <rect x="1" y="1" width="102" height="102" rx="23.4" fill={`url(#${tile})`} stroke="rgba(255,255,255,0.14)" stroke-width="2" />
      <circle cx="10.5" cy="52" r="3.9" fill="#ff6b57" />
      {bars.map(([x, h], i) => (
        <rect x={x - 1.2} y={52 - h / 2} width="6.03" height={h} rx="3.02" fill="#fff" fill-opacity={0.52 + (0.48 * i) / 7} />
      ))}
    </svg>
  );
}
